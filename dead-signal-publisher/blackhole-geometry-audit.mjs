import fs from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const key=process.env.ROBLOX_API_KEY;
if(!key)throw Error('Missing ROBLOX_API_KEY');
const r=await fetch('https://apis.roblox.com/asset-delivery-api/v1/assetId/7208091524',{headers:{'x-api-key':key}});
if(!r.ok)throw Error('Asset metadata unavailable: '+r.status);
const a=await r.json();
const loc=a.location||a.locations?.[0]?.location;
if(!loc)throw Error('No source asset link');
const raw=await fetch(loc);if(!raw.ok)throw Error('Original asset unavailable: '+raw.status);
await fs.writeFile('/tmp/asset-7208091524.rbxl',Buffer.from(await raw.arrayBuffer()));
const lune=await fetch('https://github.com/lune-org/lune/releases/download/v0.11.1/lune-0.11.1-linux-x86_64.zip');
if(!lune.ok)throw Error('Lune download unavailable');
const zip=Buffer.from(await lune.arrayBuffer());
if(createHash('sha256').update(zip).digest('hex')!=='39859282ce677fce19e6eb45c37596a90a25c324c95b4e7e02d428b6cae294a1')throw Error('Lune checksum');
await fs.writeFile('/tmp/blackhole-lune.zip',zip);
execFileSync('unzip',['-o','/tmp/blackhole-lune.zip','-d','/tmp/blackhole-lune']);
await fs.chmod('/tmp/blackhole-lune/lune',0o755);
execFileSync('/tmp/blackhole-lune/lune',['run','blackhole-audit.luau'],{cwd:new URL('.',import.meta.url),stdio:'inherit'});
